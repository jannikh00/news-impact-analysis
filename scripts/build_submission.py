"""Assemble the course submission folder and zip from the repository.

The supplied ``Assignment_3/`` layout is rebuilt from ``pipeline/`` (file names
unchanged), with the generated CSVs that fit the upload, the helper scripts,
tests and result tables. Left out, as the assignment requires or for size: the
original news archive, ``historical_impacts_values.csv`` and the four vector
CSVs (regenerated by scripts 1 and 2), caches, pipeline outputs and manifests.

Usage:
    python scripts/build_submission.py [--dest DIR] [--report FILE]
"""

import argparse
import shutil
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PIPELINE_FILES = ["1_calculate_impacts_values.py", "2_sampling_vectorize.py", "3_classify.py", "4_regression.py",
                  "utils.py", "prepare_data.py", "webscraping.py", "webscraping_headless_parsing.py"]
DATASET_FILES = ["sp500.csv", "ticker_aliases.csv", "ticker_exclusions.csv", "sec_cik_overrides.csv",
                 "news.csv", "historical_prices.csv", "market_cap_sources.csv",
                 "sample_news.csv", "sample_historical_prices.csv", "sample_historical_impacts_values.csv",
                 "sample_news_dtm_train.csv", "sample_news_dtm_test.csv",
                 "sample_news_tfidf_train.csv", "sample_news_tfidf_test.csv"]
LEFT_OUT = ["historical_impacts_values.csv", "news_dtm_train.csv", "news_dtm_test.csv",
            "news_tfidf_train.csv", "news_tfidf_test.csv"]
RESULT_DIRS = ["full_sample", "model_comparison", "text", "figures"]

README = """NewsImpact - Assignment 3 submission (Jannik Hofmann, sole contributor)

The report is {report}. This folder keeps the supplied Assignment_3 layout and file names.

Contents
  1_calculate_impacts_values.py .. 4_regression.py   the four required programs
  utils.py                                           shared settings, schemas, text cleaning, model code
  prepare_data.py                                    builds news.csv and historical_prices.csv
  datasets/                                          sp500.csv, news.csv, historical_prices.csv,
                                                     market_cap_sources.csv, ticker lists, supplied samples
  scripts/                                           audits, tuning, term evidence, report figures
  tests/                                             automated tests (python -m pytest -q tests)
  results/                                           metric tables and figures used in the report

Not included
  news_datasets.zip (original news data, per the assignment) and, because of their size,
  {left_out}.
  They are regenerated by:
    python 1_calculate_impacts_values.py
    python 2_sampling_vectorize.py

Running (Python 3.12, pip install -r requirements.txt)
  python 1_calculate_impacts_values.py
  python 2_sampling_vectorize.py
  python 3_classify.py
  python 4_regression.py
  To rebuild news.csv and historical_prices.csv from scratch, put news_datasets.zip into datasets/,
  set SEC_USER_AGENT="Name email" and run python prepare_data.py (about 1 hour, needs internet).
"""


def copy(src, dst):
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, dst)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--dest", type=Path, default=ROOT.parent / "submission")
    ap.add_argument("--report", type=Path, help="report file to place next to Assignment_3/")
    args = ap.parse_args()

    target = args.dest / "Assignment_3"
    if target.exists():
        shutil.rmtree(target)
    for name in PIPELINE_FILES:
        copy(ROOT / "pipeline" / name, target / name)
    for name in DATASET_FILES:
        copy(ROOT / "pipeline" / "datasets" / name, target / "datasets" / name)
    for folder in ["scripts", "tests"]:
        shutil.copytree(ROOT / folder, target / folder, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    for folder in RESULT_DIRS:
        shutil.copytree(ROOT / "results" / folder, target / "results" / folder)
    copy(ROOT / "requirements.txt", target / "requirements.txt")
    report_name = args.report.name if args.report else "the separate report file"
    (target / "README.txt").write_text(README.format(report=report_name, left_out=", ".join(LEFT_OUT)))
    if args.report:
        copy(args.report, args.dest / args.report.name)

    zip_path = args.dest / "Assignment_3_submission.zip"
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
        for path in sorted(p for p in args.dest.rglob("*") if p.is_file() and p != zip_path):
            zf.write(path, path.relative_to(args.dest))
    size = sum(p.stat().st_size for p in target.rglob("*") if p.is_file())
    print(f"{target}: {size / 1e6:.0f} MB; zip {zip_path.stat().st_size / 1e6:.0f} MB")


if __name__ == "__main__":
    main()
